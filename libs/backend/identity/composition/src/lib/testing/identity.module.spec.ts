const DAY: number = 24 * 60 * MINUTE;

/**
 * Interface Harness
 * @interface Harness
 *
 * @description
 * Running identity application with its clock, TOTP secrets and HTTP helpers.
 */
interface Harness {
  // #region Properties
  /**
   * Property app
   * @readonly
   *
   * @description
   * Nest application created from the identity dynamic module.
   *
   * @type {INestApplication<NodeHttpServer>}
   */
  readonly app: INestApplication<NodeHttpServer>;

  /**
   * Property clock
   * @readonly
   *
   * @description
   * Mutable deterministic time source shared with the identity use cases.
   *
   * @type {{ current: Date; now: () => Date }}
   */
  readonly clock: { current: Date; now: () => Date };

  /**
   * Property secrets
   * @readonly
   *
   * @description
   * TOTP secrets of the two accounts, keyed by e-mail address.
   *
   * @type {Map<string, string>}
   */
  readonly secrets: Map<string, string>;

  /**
   * Property keysDir
   * @readonly
   *
   * @description
   * Temporary directory containing the generated signing key.
   *
   * @type {string}
   */
  readonly keysDir: string;
  // #endregion
}

/**
 * Function start
 *
 * @description
 * Starts the identity module on an in-memory database with the administrator and a second account.
 *
 * @param {boolean} cookieSecure - Whether the cookies are `Secure` with the `__Host-` prefix.
 *
 * @returns {Promise<Harness>} Running application and its test state.
 */
async function start(cookieSecure: boolean): Promise<Harness> {
  const keysDir: string = mkdtempSync(join(tmpdir(), 'identity-keys-'));
  await generateSigningKey(keysDir, 'k1');
  const clock: { current: Date; now: () => Date } = {
    current: new Date('2026-11-02T10:00:00Z'),
    now: (): Date => new Date(clock.current),
  };
  const secrets: Map<string, string> = new Map<string, string>();
  const moduleRef: TestingModule = await Test.createTestingModule({
    imports: [
      ObservabilityModule.forRoot({ service: 'identity-test', level: 'silent', pretty: false }),
      IdentityModule.register({
        databaseUrl: 'pglite:memory',
        keysDir,
        signingKid: 'k1',
        issuer: ISSUER,
        cookieSecure,
        clock,
        prepare: async (database): Promise<void> => {
          await migrateIdentityDatabase(database, MIGRATIONS);
          const accounts: DrizzleAdminAccountRepository = new DrizzleAdminAccountRepository(
            database.db,
          );
          const hasher: ScryptPasswordHasher = new ScryptPasswordHasher();
          const totp: RfcTotpVerifier = new RfcTotpVerifier();
          const result: BootstrapResult = await new BootstrapAdmin(
            accounts,
            hasher,
            totp,
            new RandomIdGenerator(),
          ).execute(ADMIN.email, ADMIN.password);
          secrets.set(ADMIN.email, result.totpSecret);
          // A second account cannot be bootstrapped: inserted directly.
          const otherSecret: string = totp.generateSecret();
          await accounts.add(
            AdminAccount.create({
              id: 'other',
              email: OTHER.email,
              passwordHash: await hasher.hash(OTHER.password),
              totpSecret: otherSecret,
            }),
          );
          secrets.set(OTHER.email, otherSecret);
        },
      }),
    ],
  }).compile();
  const app: INestApplication<NodeHttpServer> =
    moduleRef.createNestApplication<INestApplication<NodeHttpServer>>();
  app.setGlobalPrefix('api', { exclude: ['health/live', 'health/ready'] });
  await app.init();
  return { app, clock, secrets, keysDir };
}

/**
 * Function setCookies
 *
 * @description
 * Returns every Set-Cookie header of a response.
 *
 * @param {request.Response} response - HTTP response returned by Supertest.
 *
 * @returns {string[]} Header values, empty when absent.
 */
const setCookies = (response: request.Response): string[] => {
  const header: string | string[] | undefined = response.headers['set-cookie'] as
    string[] | string | undefined;
  return header === undefined ? [] : ([] as string[]).concat(header);
};

/**
 * Function cookie
 *
 * @description
 * Finds the Set-Cookie header of one cookie.
 *
 * @param {request.Response} response - HTTP response returned by Supertest.
 * @param {string} name - Cookie name.
 *
 * @returns {string} Full header value, or an empty string when the cookie was not set.
 */
const cookie = (response: request.Response, name: string): string =>
  setCookies(response).find((header: string): boolean => header.startsWith(`${name}=`)) ?? '';

/**
 * Function pair
 *
 * @description
 * Extracts the `name=value` pair of one cookie, ready for a `Cookie` request header.
 *
 * @param {request.Response} response - HTTP response returned by Supertest.
 * @param {string} name - Cookie name.
 *
 * @returns {string} Cookie pair, or an empty string when the cookie was not set.
 */
const pair = (response: request.Response, name: string): string =>
  cookie(response, name).split(';')[0] ?? '';

/**
 * Typed browser-like HTTP helpers for the identity integration tests.
 */
interface IdentityClient {
  server(): ReturnType<typeof request>;
  code(email?: string): string;
  wrongCode(): string;
  nextStep(): void;
  advance(ms: number): void;
  password(body: object, cookies?: string): request.Test;
  submitCode(challenge: string, totp: string, trustDevice?: boolean): request.Test;
  signIn(options?: {
    account?: typeof ADMIN;
    remember?: boolean;
    trustDevice?: boolean;
  }): Promise<request.Response>;
  post(path: string, cookies: string): request.Test;
}

/**
 * Function client
 *
 * @description
 * Builds the HTTP helpers of a harness for one account.
 *
 * @param {Harness} harness - Running application.
 *
 * @returns {IdentityClient} Step, sign-in and code helpers.
 */
function client(harness: Harness): IdentityClient {
  const { app, clock, secrets } = harness;
  const server = (): ReturnType<typeof request> => request(app.getHttpServer());
  const step = (): number => Math.floor(clock.current.getTime() / 30_000);
  /**
   * Function code
   *
   * @description
   * Generates the TOTP value of an account at the injected clock's current step.
   *
   * @param {string} email - Account address.
   *
   * @returns {string} Six-digit code.
   */
  const code = (email: string = ADMIN.email): string => totpAt(secrets.get(email) ?? '', step());
  /**
   * Function wrongCode
   *
   * @description
   * Returns a six-digit code accepted in none of the steps of the verification window.
   *
   * @returns {string} Wrong code.
   */
  const wrongCode = (): string => {
    const window: string[] = [-1, 0, 1].map((d: number): string =>
      totpAt(secrets.get(ADMIN.email) ?? '', step() + d),
    );
    let candidate: number = 0;
    while (window.includes(String(candidate).padStart(6, '0'))) candidate++;
    return String(candidate).padStart(6, '0');
  };
  /**
   * Function nextStep
   *
   * @description
   * Advances the clock by one TOTP period so the next code is not a replay.
   *
   * @returns {void} Completes after the clock advances.
   */
  const nextStep = (): void => {
    clock.current = new Date(clock.current.getTime() + 30_000);
  };
  /**
   * Function advance
   *
   * @description
   * Advances the clock.
   *
   * @param {number} ms - Milliseconds to add.
   *
   * @returns {void} Completes after the clock advances.
   */
  const advance = (ms: number): void => {
    clock.current = new Date(clock.current.getTime() + ms);
  };
  /**
   * Function password
   *
   * @description
   * Sends the first login step, optionally with cookies.
   *
   * @param {object} body - First-step payload.
   * @param {string} cookies - `Cookie` header value.
   *
   * @returns {request.Test} Supertest request.
   */
  const password = (body: object, cookies: string = ''): request.Test => {
    const call: request.Test = server().post('/api/auth/login');
    return (cookies ? call.set('cookie', cookies) : call).send(body);
  };
  /**
   * Function submitCode
   *
   * @description
   * Sends the second login step with the anti-CSRF header.
   *
   * @param {string} challenge - Challenge of the first step.
   * @param {string} totp - One-time code.
   * @param {boolean} trustDevice - Whether to trust the browser.
   *
   * @returns {request.Test} Supertest request.
   */
  const submitCode = (
    challenge: string,
    totp: string,
    trustDevice: boolean = false,
  ): request.Test =>
    server().post('/api/auth/login/totp').set('x-csrf', '1').send({ challenge, totp, trustDevice });
  /**
   * Function signIn
   *
   * @description
   * Runs both login steps for an account with a fresh code.
   *
   * @param {{ account?: typeof ADMIN; remember?: boolean; trustDevice?: boolean }} options - Account and choices.
   *
   * @returns {Promise<request.Response>} request.Response of the second step.
   */
  const signIn = async (
    options: { account?: typeof ADMIN; remember?: boolean; trustDevice?: boolean } = {},
  ): Promise<request.Response> => {
    const account: { email: string; password: string } = options.account ?? ADMIN;
    nextStep();
    const first: request.Response = await password({
      ...account,
      remember: options.remember ?? true,
    });
    expect(first.body.status).toBe('totp-required');
    return submitCode(first.body.challenge, code(account.email), options.trustDevice ?? false);
  };
  /**
   * Function post
   *
   * @description
   * Sends a cookie-backed request with the anti-CSRF header.
   *
   * @param {string} path - Route under `/api/auth`.
   * @param {string} cookies - `Cookie` header value.
   *
   * @returns {request.Test} Supertest request.
   */
  const post = (path: string, cookies: string): request.Test =>
    server().post(`/api/auth/${path}`).set('cookie', cookies).set('x-csrf', '1');
  return { server, code, wrongCode, nextStep, advance, password, submitCode, signIn, post };
}

describe('IdentityModule', (): void => {
  /**
   * Variable harness
   *
   * @description
   * Application with secure (`__Host-`) cookies.
   *
   * @type {Harness}
   */
  let harness: Harness;

  /**
   * Variable http
   *
   * @description
   * HTTP helpers bound to the harness.
   *
   * @type {ReturnType<typeof client>}
   */
  let http: ReturnType<typeof client>;

  const REFRESH = '__Host-portfolio_refresh' as const;
  const DEVICE = '__Host-portfolio_device' as const;

  beforeAll(async (): Promise<void> => {
    harness = await start(true);
    http = client(harness);
  });

  afterAll(async (): Promise<void> => {
    await harness.app.close();
    rmSync(harness.keysDir, { recursive: true, force: true });
  });

  it('rejects wrong credentials without saying which ones', async (): Promise<void> => {
    const response: request.Response = await http.password({
      ...ADMIN,
      password: 'wrong',
      remember: true,
    });
    expect(response.status).toBe(401);
    expect(response.body.code).toBe('identity.invalid-credentials');
  });

  it('asks for the code, then opens a remembered session with an at+jwt access token', async (): Promise<void> => {
    http.nextStep();
    const first: request.Response = await http.password({ ...ADMIN, remember: true });
    expect(first.status).toBe(200);
    expect(first.headers['cache-control']).toBe('no-store');
    expect(first.body).toEqual({
      status: 'totp-required',
      challenge: expect.stringMatching(/^[\w-]{43}$/),
      expiresIn: 300,
    });
    expect(setCookies(first)).toEqual([]);

    const noCsrf: request.Response = await http
      .server()
      .post('/api/auth/login/totp')
      .send({ challenge: first.body.challenge, totp: http.code(), trustDevice: false });
    expect(noCsrf.status).toBe(403);

    const second: request.Response = await http.submitCode(first.body.challenge, http.code());
    expect(second.status).toBe(200);
    expect(second.headers['cache-control']).toBe('no-store');
    const expires: string = new Date(harness.clock.current.getTime() + 30 * DAY).toUTCString();
    expect(setCookies(second)).toEqual([
      expect.stringMatching(
        new RegExp(
          `^${REFRESH}=[\\w-]{43}; Path=/; Expires=${expires}; HttpOnly; Secure; SameSite=Strict$`,
        ),
      ),
    ]);

    const jwks: JSONWebKeySet = (await http.server().get('/api/auth/jwks.json')).body;
    const { payload, protectedHeader } = await jwtVerify(
      second.body.accessToken,
      createLocalJWKSet(jwks),
      {
        issuer: ISSUER,
        audience: 'portfolio-admin',
        algorithms: ['EdDSA'],
        typ: 'at+jwt',
        requiredClaims: ['sid', 'jti', 'nbf'],
        currentDate: harness.clock.now(),
      },
    );
    expect(protectedHeader.typ).toBe('at+jwt');
    expect(payload['role']).toBe('admin');
    expect(Number(payload.exp) - Number(payload.iat)).toBe(300);
    expect(second.body.expiresIn).toBe(300);
  });

  it('sets a browser-session refresh cookie without "remember me", kept on refresh', async (): Promise<void> => {
    const response: request.Response = await http.signIn({ remember: false });
    expect(cookie(response, REFRESH)).toMatch(
      new RegExp(`^${REFRESH}=[\\w-]{43}; Path=/; HttpOnly; Secure; SameSite=Strict$`),
    );
    const refreshed: request.Response = await http.post('refresh', pair(response, REFRESH));
    expect(refreshed.status).toBe(200);
    expect(cookie(refreshed, REFRESH)).not.toContain('Expires');
  });

  it('trusts the device: the next password login skips the code', async (): Promise<void> => {
    const response: request.Response = await http.signIn({ trustDevice: true });
    const expires: string = new Date(harness.clock.current.getTime() + 30 * DAY).toUTCString();
    expect(cookie(response, DEVICE)).toMatch(
      new RegExp(
        `^${DEVICE}=[\\w-]{43}; Path=/; Expires=${expires}; HttpOnly; Secure; SameSite=Strict$`,
      ),
    );
    const again: request.Response = await http.password(
      { ...ADMIN, remember: true },
      pair(response, DEVICE),
    );
    expect(again.status).toBe(200);
    expect(again.body).toEqual({
      status: 'authenticated',
      accessToken: expect.any(String),
      expiresIn: 300,
    });
    expect(cookie(again, REFRESH)).toMatch(new RegExp(`^${REFRESH}=`));
    const wrong: request.Response = await http.password(
      { ...ADMIN, password: 'wrong', remember: true },
      pair(response, DEVICE),
    );
    expect(wrong.status).toBe(401);
  });

  it('ignores a device trusted by another account', async (): Promise<void> => {
    const other: request.Response = await http.signIn({ account: OTHER, trustDevice: true });
    expect(other.status).toBe(200);
    const response: request.Response = await http.password(
      { ...ADMIN, remember: true },
      pair(other, DEVICE),
    );
    expect(response.body.status).toBe('totp-required');
  });

  it('logs out the session but keeps the device cookie and its trust', async (): Promise<void> => {
    const response: request.Response = await http.signIn({ trustDevice: true });
    const cookies: string = `${pair(response, REFRESH)}; ${pair(response, DEVICE)}`;
    const out: request.Response = await http.post('logout', cookies);
    expect(out.status).toBe(204);
    expect(setCookies(out)).toEqual([
      `${REFRESH}=; Path=/; Expires=Thu, 01 Jan 1970 00:00:00 GMT; HttpOnly; Secure; SameSite=Strict`,
    ]);
    expect((await http.post('refresh', pair(response, REFRESH))).status).toBe(401);
    const again: request.Response = await http.password(
      { ...ADMIN, remember: true },
      pair(response, DEVICE),
    );
    expect(again.body.status).toBe('authenticated');
  });

  it('rotates the refresh token, and revokes the session if an old cookie is replayed', async (): Promise<void> => {
    const first: string = pair(await http.signIn(), REFRESH);
    expect((await http.server().post('/api/auth/refresh').set('cookie', first)).status).toBe(403);
    const rotated: request.Response = await http.post('refresh', first);
    expect(rotated.status).toBe(200);
    const second: string = pair(rotated, REFRESH);
    expect(second).not.toBe(first);

    const replay: request.Response = await http.post('refresh', first);
    expect(replay.status).toBe(401);
    expect(replay.body.code).toBe('identity.invalid-session');
    expect((await http.post('refresh', second)).status).toBe(401);
  });

  it('refuses a challenge used twice', async (): Promise<void> => {
    http.nextStep();
    const first: request.Response = await http.password({ ...ADMIN, remember: true });
    expect((await http.submitCode(first.body.challenge, http.code())).status).toBe(200);
    http.nextStep();
    const replay: request.Response = await http.submitCode(first.body.challenge, http.code());
    expect(replay.status).toBe(401);
    expect(replay.body.code).toBe('identity.challenge-expired');
  });

  it('refuses a challenge after five minutes', async (): Promise<void> => {
    http.nextStep();
    const first: request.Response = await http.password({ ...ADMIN, remember: true });
    http.advance(5 * 60_000);
    const late: request.Response = await http.submitCode(first.body.challenge, http.code());
    expect(late.status).toBe(401);
    expect(late.body.code).toBe('identity.challenge-expired');
  });

  it('counts wrong codes toward the lockout and ends the challenge after five', async (): Promise<void> => {
    http.nextStep();
    const first: request.Response = await http.password({ ...ADMIN, remember: true });
    for (let i: number = 0; i < 5; i++) {
      const wrong: request.Response = await http.submitCode(first.body.challenge, http.wrongCode());
      expect(wrong.status).toBe(401);
      expect(wrong.body.code).toBe('identity.invalid-credentials');
    }
    const exhausted: request.Response = await http.submitCode(first.body.challenge, http.code());
    expect(exhausted.body.code).toBe('identity.challenge-expired');
    const locked: request.Response = await http.password({ ...ADMIN, remember: true });
    expect(locked.status).toBe(401);
    expect(locked.body.code).toBe('identity.invalid-credentials');

    http.advance(15 * MINUTE);
    expect((await http.signIn()).status).toBe(200);
  });

  it('asks for the code again once the device trust expired', async (): Promise<void> => {
    const response: request.Response = await http.signIn({ trustDevice: true });
    http.advance(30 * DAY);
    const again: request.Response = await http.password(
      { ...ADMIN, remember: true },
      pair(response, DEVICE),
    );
    expect(again.body.status).toBe('totp-required');
  });
});

describe('IdentityModule over plain HTTP (development)', (): void => {
  /**
   * Variable harness
   *
   * @description
   * Application without secure cookies.
   *
   * @type {Harness}
   */
  let harness: Harness;

  beforeAll(async (): Promise<void> => {
    harness = await start(false);
  });

  afterAll(async (): Promise<void> => {
    await harness.app.close();
    rmSync(harness.keysDir, { recursive: true, force: true });
  });

  it('uses plain cookie names on /api/auth, without Secure', async (): Promise<void> => {
    const http: IdentityClient = client(harness);
    const response: request.Response = await http.signIn({ trustDevice: true });
    expect(cookie(response, 'portfolio_refresh')).toMatch(
      /^portfolio_refresh=[\w-]{43}; Path=\/api\/auth; Expires=[^;]+; HttpOnly; SameSite=Strict$/,
    );
    expect(cookie(response, 'portfolio_device')).toMatch(
      /^portfolio_device=[\w-]{43}; Path=\/api\/auth; Expires=[^;]+; HttpOnly; SameSite=Strict$/,
    );
    const again: request.Response = await http.password(
      { ...ADMIN, remember: false },
      pair(response, 'portfolio_device'),
    );
    expect(again.body.status).toBe('authenticated');
    expect(cookie(again, 'portfolio_refresh')).toMatch(
      /^portfolio_refresh=[\w-]{43}; Path=\/api\/auth; HttpOnly; SameSite=Strict$/,
    );
    const out: request.Response = await http.post('logout', pair(again, 'portfolio_refresh'));
    expect(setCookies(out)).toEqual([
      'portfolio_refresh=; Path=/api/auth; Expires=Thu, 01 Jan 1970 00:00:00 GMT; HttpOnly; SameSite=Strict',
    ]);
  });
});
